import { cp, mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import {
  loadConfig,
  resolveEntryFile,
  walkFiles,
  zipFiles,
  SKIP_DIRS,
  SKIP_FILES,
} from "@appbeam/pipeline";
import type { ArchiveFile } from "@appbeam/pipeline";
import { parseSessionId, readSessionCode } from "@/lib/server/sessions";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

const README_NAME = "README-APPBEAM.txt";

const README = `Appbeam export
==============

This archive is a complete Expo project (React Native + React Native Web).
The generated app lives in App.tsx — a single self-contained component.

  npm install        # install dependencies
  npx expo start     # dev server — scan the QR with Expo Go, or press "w" for web
  npm run web        # shortcut: react-native-web in the browser
  npm run build      # static web export into dist/

Third-party APIs recovered from the original app are served by the in-file
mock layer, so the project runs offline with no backend keys required.

Generated by appbeam — https://github.com/alanhu0513-oss/appbeam
`;

function copyFilter(src: string): boolean {
  const name = src.split(/[/\\]/).pop() ?? "";
  return !SKIP_DIRS.has(name) && !SKIP_FILES.has(name);
}

/**
 * Zip the template with the visitor's session-generated App.tsx overlaid
 * on top — required because hosted instances deploy from staged copies
 * and never mutate the shared template directory.
 */
async function zipWithOverlay(
  templateDir: string,
  entryFile: string,
  code: string,
): Promise<Buffer> {
  const stagingRoot = join(tmpdir(), "appbeam-export");
  await mkdir(stagingRoot, { recursive: true });
  const copy = await mkdtemp(join(stagingRoot, "exp-"));
  try {
    await cp(templateDir, copy, { recursive: true, filter: copyFilter });
    await writeFile(join(copy, entryFile), code, "utf8");
    return await zipSessionFiles(copy);
  } finally {
    await rm(copy, { recursive: true, force: true });
  }
}

async function zipSessionFiles(dir: string): Promise<Buffer> {
  const files: ArchiveFile[] = await walkFiles(dir);
  files.push({ file: README_NAME, data: Buffer.from(README, "utf8") });
  return zipFiles(files);
}

/**
 * GET /api/export — package the current simulator project as a `.zip` and
 * stream it to the browser. Pass `?session=<id>` (or the x-appbeam-session
 * header) to overlay that visitor's generated App.tsx; without a session the
 * shared template is exported as-is. README with run instructions is
 * appended so the unpacked project boots immediately.
 */
export async function GET(req: Request): Promise<Response> {
  try {
    const config = loadConfig();
    const entryFile = resolveEntryFile(config.templateDir);
    const sessionId =
      parseSessionId(req.headers.get("x-appbeam-session")) ??
      parseSessionId(new URL(req.url).searchParams.get("session"));
    const sessionCode = sessionId ? await readSessionCode(sessionId) : null;

    let zip: Buffer;
    if (sessionCode) {
      zip = await zipWithOverlay(config.templateDir, entryFile, sessionCode);
    } else {
      const files = await walkFiles(config.templateDir);
      if (files.length === 0) {
        return Response.json(
          { error: `No files found in ${config.templateDir}` },
          { status: 404 },
        );
      }
      zip = await zipSessionFiles(config.templateDir);
    }

    const filename = `${config.vercelProjectName}-expo.zip`;
    return new Response(new Uint8Array(zip), {
      headers: {
        "Content-Type": "application/zip",
        "Content-Disposition": `attachment; filename="${filename}"`,
        "Content-Length": String(zip.byteLength),
        "Cache-Control": "no-store",
      },
    });
  } catch (err) {
    return Response.json(
      { error: err instanceof Error ? err.message : String(err) },
      { status: 500 },
    );
  }
}
